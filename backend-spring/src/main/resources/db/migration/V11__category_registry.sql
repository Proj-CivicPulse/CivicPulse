-- Canonical category registry.
--
-- Until now `category` was a free-form VARCHAR written by whoever was calling:
-- the submit form's own hardcoded vocabulary, and whatever an API client sent.
-- Nothing stopped 'garbage', 'Garbage', 'Solid Waste' and 'uncollected garbage'
-- from coexisting, and every consumer treats category as an EXACT-equality key
-- -- the semantic matcher's candidate pre-filter (ward + category + status),
-- the naive fallback, the dashboard breakdown. Four spellings of one problem
-- therefore mean four incidents that never merge and four dashboard rows.
--
-- The fix is a registry with aliases, not fuzzy matching at query time:
-- normalise once on the way in, then keep comparing exact canonical codes. The
-- matching SQL in backend-node is untouched by this migration, by design.
--
-- `code` is the canonical identifier and stays the value stored in
-- complaints.category / incidents.category, so existing rows, indexes and the
-- Node matcher keep working unchanged. The raw string the caller sent is
-- preserved alongside it in `source_category` for audit and debugging.

CREATE TABLE categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Stable, lowercase, never renamed. This is what lands in
    -- complaints.category and what every filter compares against.
    code         VARCHAR(64)  NOT NULL,
    -- Officer-facing canonical name.
    name         VARCHAR(255) NOT NULL,
    -- Resident-facing label on the submit form. Separate from `name` because
    -- the two audiences genuinely want different words for the same thing.
    display_name VARCHAR(255) NOT NULL,
    -- Retired categories stay readable (old complaints still reference them)
    -- but drop out of the submit form and stop being accepted on new reports.
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    -- Optional rollup, e.g. a future 'pothole' under 'roads'. Unused at seed
    -- time; present so introducing a hierarchy later is not another migration
    -- of every consumer.
    parent_id    BIGINT,
    -- Submit-form ordering. 'other' sorts last deliberately.
    sort_order   INTEGER      NOT NULL DEFAULT 0,
    created_at   TIMESTAMP(6) NOT NULL,
    updated_at   TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_categories_code UNIQUE (code),
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id)
);

-- Every accepted spelling of a category, stored ALREADY NORMALISED: lowercased,
-- with each run of non-alphanumeric characters collapsed to one space, trimmed.
-- CategoryNormalizer.normalise() in backend-spring applies the identical
-- transform to incoming values, so resolution is a plain equality hit on this
-- table and never a LIKE or a similarity search.
--
-- Canonical codes are themselves seeded as aliases, so resolution is one query.
CREATE TABLE category_aliases (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT       NOT NULL,
    alias       VARCHAR(128) NOT NULL,
    -- Which vocabulary this spelling came from. 'internal' is our own UI and
    -- API surface; an external feed gets its own source row so a term that
    -- means something different over there cannot hijack our vocabulary.
    source      VARCHAR(64)  NOT NULL DEFAULT 'internal',
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_category_aliases_source_alias UNIQUE (source, alias),
    CONSTRAINT fk_category_aliases_category
        FOREIGN KEY (category_id) REFERENCES categories (id)
);

CREATE INDEX idx_category_aliases_alias ON category_aliases (alias);

