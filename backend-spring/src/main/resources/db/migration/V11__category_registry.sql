-- The raw string the caller sent, kept so a normalisation decision is always
-- reversible and auditable. NULL on rows created before this migration, where
-- the stored value WAS the raw value.
ALTER TABLE complaints ADD COLUMN source_category VARCHAR(255);
ALTER TABLE incidents  ADD COLUMN source_category VARCHAR(255);

-- Backfill: fold existing rows onto canonical codes wherever an alias resolves
-- them, preserving what was there first.
--
-- Rows that resolve to NOTHING are deliberately LEFT ALONE rather than swept
-- into 'other'. Forcing an unrecognised value into 'other' would merge
-- genuinely unrelated complaints into one candidate pool -- a worse fault than
-- the fragmentation this migration exists to fix -- and it would do so
-- irreversibly for anyone reading `category` alone. Leaving them is simply the
-- status quo: they keep grouping only with their own spelling.
--
-- To find what was left behind (the quarantine report):
--   SELECT category, COUNT(*) FROM complaints
--   WHERE category NOT IN (SELECT code FROM categories)
--   GROUP BY category ORDER BY 2 DESC;
UPDATE complaints c
SET source_category = c.category,
    category        = cat.code
FROM category_aliases a
JOIN categories cat ON cat.id = a.category_id
WHERE a.source = 'internal'
  AND a.alias = btrim(regexp_replace(lower(c.category), '[^a-z0-9]+', ' ', 'g'))
  AND c.category <> cat.code;

UPDATE incidents i
SET source_category = i.category,
    category        = cat.code
FROM category_aliases a
JOIN categories cat ON cat.id = a.category_id
WHERE a.source = 'internal'
  AND a.alias = btrim(regexp_replace(lower(i.category), '[^a-z0-9]+', ' ', 'g'))
  AND i.category <> cat.code;
