-- Persist dataset validation results instead of shouting them into a log.
--
-- V13 checked a great deal on the way in -- ward count, geometry validity,
-- centroid containment, and how far ST_MakeValid moved each repaired boundary
-- -- and reported all of it with RAISE NOTICE. A notice is not a record. It
-- cannot be queried, compared against the next import, alerted on, or shown to
-- anyone asking "how good is this ward data?". It survives exactly as long as
-- whoever happened to be watching the deploy output.
--
-- This table is that record. It is deliberately GENERIC rather than
-- area-specific: the same shape holds a ward count, a validity count, a
-- centroid check and an area drift, so the next dataset (a new delimitation,
-- a category import, an external feed's reference data) does not need another
-- table.

CREATE TABLE dataset_validations (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- What was checked, e.g. 'bbmp-wards'.
    dataset_name    VARCHAR(64)  NOT NULL,
    -- Which revision of it, so results are comparable across imports.
    dataset_version VARCHAR(32)  NOT NULL,
    -- Which check, e.g. 'ward-count', 'geometry-validity', 'repair-area-drift'.
    check_name      VARCHAR(64)  NOT NULL,
    -- The individual row checked, where the check is per-row (a ward code).
    -- NULL for a whole-dataset check.
    subject         VARCHAR(128),
    -- PASS | WARN | FAIL. WARN exists because some findings are real and
    -- tolerable -- 45 wards with no LGD code is a fact about the source, not a
    -- reason to refuse the import.
    status          VARCHAR(8)   NOT NULL,
    observed        DOUBLE PRECISION,
    threshold       DOUBLE PRECISION,
    unit            VARCHAR(32),
    detail          TEXT,
    checked_at      TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_dataset_validations_status
        CHECK (status IN ('PASS', 'WARN', 'FAIL'))
);

CREATE INDEX idx_dataset_validations_lookup
    ON dataset_validations (dataset_name, dataset_version, checked_at DESC);
CREATE INDEX idx_dataset_validations_status
    ON dataset_validations (status) WHERE status <> 'PASS';

COMMENT ON TABLE dataset_validations IS
    'Import-time data quality results. One row per check per dataset version. '
    'Query WHERE status <> ''PASS'' for everything currently known to be wrong '
    'or tolerated in reference data.';

-- Backfill what the V13 import established.
--
-- Most of these are RE-DERIVED from the current rows, so they are measurements
-- rather than recollections. The exception is the repair drift: ST_MakeValid
-- has already run and the pre-repair geometry no longer exists, so that one row
-- is transcribed from the V13 migration output and says so in its detail.
INSERT INTO dataset_validations
    (dataset_name, dataset_version, check_name, subject, status,
     observed, threshold, unit, detail, checked_at)
SELECT 'bbmp-wards', '2022-delimitation', v.check_name, v.subject, v.status,
       v.observed, v.threshold, v.unit, v.detail, NOW()
FROM (
    VALUES
    ('ward-count', NULL,
     (SELECT CASE WHEN COUNT(*) = 243 THEN 'PASS' ELSE 'FAIL' END
        FROM wards WHERE source = 'kgis-bbmp-2022'),
     (SELECT COUNT(*)::double precision FROM wards WHERE source = 'kgis-bbmp-2022'),
     243::double precision, 'wards',
     'Expected ward count for the 2022 delimitation.'),

    ('geometry-validity', NULL,
     (SELECT CASE WHEN COUNT(*) FILTER (WHERE NOT ST_IsValid(boundary)) = 0
                  THEN 'PASS' ELSE 'FAIL' END
        FROM wards WHERE source = 'kgis-bbmp-2022'),
     (SELECT COUNT(*) FILTER (WHERE NOT ST_IsValid(boundary))::double precision
        FROM wards WHERE source = 'kgis-bbmp-2022'),
     0::double precision, 'invalid geometries',
     'Boundaries PostGIS will not answer ST_Contains on reliably.'),

    ('centroid-containment', NULL,
     (SELECT CASE WHEN COUNT(*) FILTER (WHERE NOT ST_Intersects(
                        boundary, ST_SetSRID(ST_MakePoint(longitude, latitude), 4326))) = 0
                  THEN 'PASS' ELSE 'FAIL' END
        FROM wards WHERE source = 'kgis-bbmp-2022'),
     (SELECT COUNT(*) FILTER (WHERE NOT ST_Intersects(
                        boundary, ST_SetSRID(ST_MakePoint(longitude, latitude), 4326)))::double precision
        FROM wards WHERE source = 'kgis-bbmp-2022'),
     0::double precision, 'centroids outside their ward',
     'ST_PointOnSurface guarantees this; a failure means the derivation changed.'),

    ('repair-area-drift', NULL, 'PASS',
     0.0::double precision, 0.5::double precision, 'percent',
     'Five self-intersecting boundaries repaired with ST_MakeValid during V13; '
     'largest area change 0.0000 percent (ward 136 Binnipete). TRANSCRIBED from '
     'the V13 migration output -- the pre-repair geometry no longer exists to '
     'recompute from. Future imports record this themselves.'),

    ('lgd-code-coverage', NULL,
     (SELECT CASE WHEN COUNT(*) FILTER (WHERE lgd_ward_code IS NULL) = 0
                  THEN 'PASS' ELSE 'WARN' END
        FROM wards WHERE source = 'kgis-bbmp-2022'),
     (SELECT COUNT(*) FILTER (WHERE lgd_ward_code IS NULL)::double precision
        FROM wards WHERE source = 'kgis-bbmp-2022'),
     0::double precision, 'wards without an LGD code',
     'WARN, not FAIL: the 2022 delimitation created these wards and the national '
     'Local Government Directory has not issued codes for them. Absence is '
     'recorded rather than invented; see the ward_external_ids view.')
) AS v(check_name, subject, status, observed, threshold, unit, detail);

-- Post-condition: the backfill must not silently record a FAIL. If the current
-- ward rows no longer satisfy what V13 asserted, something has edited them
-- since, and that is worth stopping for.
DO $$
DECLARE
    failed INTEGER;
    names  TEXT;
BEGIN
    SELECT COUNT(*), string_agg(check_name, ', ')
      INTO failed, names
      FROM dataset_validations
     WHERE dataset_name = 'bbmp-wards' AND status = 'FAIL';

    IF failed > 0 THEN
        RAISE EXCEPTION 'ward dataset no longer passes its own import checks: %', names;
    END IF;
END $$;
