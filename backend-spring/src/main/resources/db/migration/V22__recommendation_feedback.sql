-- Officer feedback on decision-support recommendations (docs/roadmap.md,
-- Phase 11.3). One row each time an officer accepts or overrides the action
-- the rules recommended for an incident; the override rate per action is
-- the measure of whether the rules help.
--
-- recommended_action and rule_id are what the SERVER recommended at that
-- moment, recomputed when the feedback is posted — never taken from the
-- client — so the log cannot record a recommendation that was never made.
--
-- No foreign key to incidents, for the reason V7 dropped them from
-- incident_match_log: the reconcile job deletes an incident once its last
-- complaint moves off it, and an officer's decision is history that must
-- outlive that cleanup.

CREATE TABLE recommendation_feedback (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id        BIGINT       NOT NULL,
    recommended_action VARCHAR(32)  NOT NULL,
    rule_id            VARCHAR(64)  NOT NULL,
    decision           VARCHAR(16)  NOT NULL,
    chosen_action      VARCHAR(32),
    note               VARCHAR(1000),
    user_id            BIGINT       NOT NULL,
    created_at         TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_recommendation_feedback_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_recommendation_feedback_decision CHECK (decision IN ('ACCEPTED', 'OVERRIDDEN')),
    CONSTRAINT ck_recommendation_feedback_choice CHECK (
        (decision = 'ACCEPTED'   AND chosen_action IS NULL) OR
        (decision = 'OVERRIDDEN' AND chosen_action IS NOT NULL AND chosen_action <> recommended_action))
);

CREATE INDEX idx_recommendation_feedback_incident ON recommendation_feedback (incident_id, created_at DESC);
